def validate_inputs(inputs: Mapping[str, Any]) -> None:
    contract = inputs["contract"]
    require(contract.get("contract_id") == EXPECTED_CONTRACT_ID, "unexpected contract")
    require(contract.get("scope", {}).get("held_out_test") is False, "test use is forbidden")
    require(contract.get("scope", {}).get("seed") == 42, "only frozen seed42 is in scope")
    require(set(contract.get("models", {})) == set(MODEL_ORDER), "four-model contract drift")

    for split in ("validation", "train"):
        summary = inputs[f"{split}_summary"]
        audit = inputs[f"{split}_inference_audit"]
        require(summary.get("schema") == EXPECTED_ANALYSIS_SCHEMA, f"{split} schema drift")
        require(summary.get("status") == "success", f"{split} analysis not successful")
        require(summary.get("split") == split, f"{split} label drift")
        require(summary.get("primary_comparison") == PRIMARY_COMPARISON, "comparison drift")
        require(summary.get("delta_definition") == "candidate_minus_reference; negative favors candidate", "delta definition drift")
        require(summary.get("scope", {}).get("held_out_test_evaluated") is False, "test leakage")
        require(summary.get("scope", {}).get("paired_predictions_only") is True, "paired scope drift")
        require(set(summary.get("overall", {}).get("models", {})) == set(MODEL_ORDER), "model row drift")
        expected_count = int(contract["populations"][split]["count"])
        require(int(summary.get("row_count", -1)) == expected_count, f"{split} row count drift")
        require(int(audit.get("population", {}).get("count", -1)) == expected_count, f"{split} inference count drift")
        if split == "validation":
            require(
                audit.get("status") == "requires_numeric_compatibility_audit",
                "validation must preserve the original strict replay failure",
            )
            require(audit.get("validation_replay_passed") is False, "strict replay outcome was rewritten")
        else:
            require(audit.get("status") == "passed", "train inference audit not passed")
        require(audit.get("training") is False, f"{split} inference trained a model")
        require(audit.get("held_out_test_evaluated") is False, f"{split} audit used test")
        require(summary.get("input", {}).get("sha256") == audit.get("prediction_sha256"), f"{split} prediction provenance drift")
        require(summary.get("contract", {}).get("sha256") == sha256_file(INPUT_PATHS["contract"]), f"{split} contract digest drift")
        for artifact_name, file_key in (("strata_csv", "strata"), ("folds_csv", "folds")):
            artifact = summary.get("artifacts", {}).get(artifact_name, {})
            path = INPUT_PATHS[f"{split}_{file_key}"]
            require(artifact.get("sha256") == sha256_file(path), f"{split} {file_key} digest drift")

        overall_delta = float(summary["overall"]["comparisons"][PRIMARY_COMPARISON]["delta_mse"])
        for family, expected_labels in (
            ("quantity_band", QUANTITY_LABELS),
            ("history_band", HISTORY_LABELS),
        ):
            selected = [
                row
                for row in inputs[f"{split}_strata"]
                if row["partition_family"] == family
                and row["comparison"] == PRIMARY_COMPARISON
            ]
            require(tuple(row["group_label"] for row in selected) == expected_labels, f"{split} {family} labels drift")
            require(sum(int(row["count"]) for row in selected) == expected_count, f"{split} {family} count replay")
            _close(
                math.fsum(float(row["contribution_to_overall_delta_mse"]) for row in selected),
                overall_delta,
                f"{split} {family} contribution replay",
            )

        folds = [
            row
            for row in inputs[f"{split}_folds"]
            if row["comparison"] == PRIMARY_COMPARISON
        ]
        require(tuple(int(row["fold"]) for row in folds) == (0, 1), f"{split} fold rows drift")
        require(all(row["is_oof_generalization"] is False for row in folds), "fold cannot be OOF")
        require(sum(int(row["count"]) for row in folds) == expected_count, f"{split} fold count replay")
        _close(
            math.fsum(float(row["contribution_to_overall_delta_mse"]) for row in folds),
            overall_delta,
            f"{split} fold contribution replay",
        )

    policy = inputs["numeric_replay_policy"]
    numeric = inputs["numeric_compatibility_audit"]
    require(policy.get("policy_id") == "float32_cpu_cuda_replay_v1", "numeric policy drift")
    require(policy.get("original_contract_unchanged") is True, "numeric policy changed the contract")
    require(
        policy.get("timing")
        == "Policy fixed after original strict aggregate replay failure and before any candidate per-row analysis or train predictions.",
        "numeric policy timing drift",
    )
    require(numeric.get("status") == "passed", "numeric compatibility supplement did not pass")
    require(numeric.get("original_absolute_replay_passed") is False, "strict replay failure was hidden")
    require(numeric.get("policy_sha256") == sha256_file(INPUT_PATHS["numeric_replay_policy"]), "numeric policy digest drift")
    require(numeric.get("inference_audit_sha256") == sha256_file(INPUT_PATHS["validation_inference_audit"]), "numeric audit input drift")
    require(all(numeric.get("checks", {}).values()), "numeric compatibility checks are incomplete")
