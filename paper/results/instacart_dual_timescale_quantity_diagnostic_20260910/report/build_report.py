def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def load_json(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    require(isinstance(payload, dict), f"{path} must contain a JSON object")
    return payload


def _coerce_csv_value(value: str) -> Any:
    if value == "":
        return None
    lowered = value.lower()
    if lowered == "true":
        return True
    if lowered == "false":
        return False
    try:
        if all(character not in value for character in ".eE"):
            return int(value)
        return float(value)
    except ValueError:
        return value


def load_csv(path: Path) -> list[dict[str, Any]]:
    categorical = {"group_label", "history_band", "quantity_band", "group", "recent_sign"}
    with path.open(newline="", encoding="utf-8") as handle:
        return [
            {key: (value if key in categorical else _coerce_csv_value(value)) for key, value in row.items()}
            for row in csv.DictReader(handle)
        ]


def _repo_path(path: Path) -> str:
    return path.resolve().relative_to(REPO_ROOT).as_posix()


def _atomic_json(path: Path, payload: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    temporary.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2, allow_nan=False) + "\n",
        encoding="utf-8",
    )
    os.replace(temporary, path)


def _close(observed: float, expected: float, label: str) -> None:
    require(math.isfinite(observed) and math.isfinite(expected), f"{label} is not finite")
    tolerance = 1e-9 * max(1.0, abs(observed), abs(expected))
    require(abs(observed - expected) <= tolerance, f"{label} mismatch")


