def deliver() -> dict[str, Any]:
    require((PLUGIN_ROOT / "package.json").is_file(), "Data Analytics plugin root is unavailable")
    command = [
        "npm",
        "run",
        "report:deliver",
        "--",
        "--input",
        str(ARTIFACT_PATH),
        "--output",
        str(REPORT_PATH),
    ]
    completed = subprocess.run(
        command,
        cwd=PLUGIN_ROOT,
        text=True,
        capture_output=True,
        check=False,
    )
    output_lines = [line for line in completed.stdout.splitlines() if line.strip()]
    error_lines = [line for line in completed.stderr.splitlines() if line.strip()]
    require(completed.returncode == 0, "portable report delivery failed: " + " ".join(error_lines[-2:]))
    require(output_lines, "portable report delivery returned no receipt")
    receipt = json.loads(output_lines[-1])
    require(receipt.get("ok") is True, "portable report delivery receipt is not successful")
    require(receipt.get("stages", {}).get("validation") == "passed", "artifact validation did not pass")
    require(receipt.get("stages", {}).get("package") == "passed", "artifact packaging did not pass")
    require(receipt.get("stages", {}).get("verification") in {"passed", "structural_only"}, "artifact verification failed")
    _atomic_json(DELIVERY_RECEIPT_PATH, receipt)
    return receipt


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--artifact-only",
        action="store_true",
        help="Validate all evidence and write artifact.json without packaging report.html.",
    )
    parser.add_argument(
        "--check-inputs",
        action="store_true",
        help="Only validate that every frozen analysis input is ready and internally consistent.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    inputs = load_inputs()
    if args.check_inputs:
        print(json.dumps({"status": "ready", "inputs": {key: sha256_file(path) for key, path in INPUT_PATHS.items()}}, indent=2))
        return
    artifact = build_artifact(inputs)
    _atomic_json(ARTIFACT_PATH, artifact)
    result: dict[str, Any] = {
        "artifact": str(ARTIFACT_PATH),
        "artifact_sha256": sha256_file(ARTIFACT_PATH),
    }
    if not args.artifact_only:
        receipt = deliver()
        result.update(
            {
                "report": str(REPORT_PATH),
                "report_sha256": sha256_file(REPORT_PATH),
                "delivery_verification": receipt["stages"]["verification"],
                "delivery_receipt": str(DELIVERY_RECEIPT_PATH),
            }
        )
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
